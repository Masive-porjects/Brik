-- Repair production schema drift that made jobs 404 and sessions ephemeral.
--
-- WHY THIS MIGRATION EXISTS
-- Two tables in the live project do not match what the backend writes, and
-- both failures are silent by construction:
--
--   1. `dsp_jobs` was created by hand and is missing `meta` and
--      `lease_expires_at`. `SupabaseJobStore.create()` inserts the whole
--      JobRecord payload, so every insert raised and was swallowed by the
--      `except` that logs "Could not persist job". The endpoint still answered
--      202 with the in-memory record and the DSP ran, but the record was never
--      stored, so the FIRST POLL returned 404. Observed in production as
--      `PGRST204: Could not find the 'lease_expires_at' column of 'dsp_jobs'`.
--
--   2. `sessions` is a generic key/value table (`id`, `data`, `created_at`,
--      `updated_at`) that nothing in this codebase writes. The real schema was
--      never applied because `20261002230400_create_sessions.sql` opens with
--      `create table if not exists`: the wrong table already existed, so the
--      guard silently did nothing. `SupabaseSessionBackend.probe()` then failed
--      and the service fell back to the file mirror at
--      `/app/uploads/sessions.json`, which Railway Free wipes on every
--      redeploy -- so sessions never survived a deploy.
--
-- The original `20260930183000_create_dsp_jobs.sql` referenced by
-- 20261002230400 is not present in this repository. That is the root cause of
-- drift with no migration to catch it; these columns are now pinned here.
--
-- SAFE TO RUN MORE THAN ONCE
-- Part 1 is purely additive. Part 2 drops a table, so it is guarded: if the
-- wrong-shaped `sessions` table ever holds rows, this migration raises and
-- changes nothing instead of discarding data.

-- ── Part 1: dsp_jobs, additive ─────────────────────────────────────────────
-- `add column if not exists` keeps the existing row. No drop, no lock beyond
-- the brief one an ADD COLUMN takes, no data at risk.

alter table public.dsp_jobs
    add column if not exists meta jsonb not null default '{}'::jsonb;

-- Nullable on purpose: a terminal job clears its lease, and a job that was
-- never leased has no expiry. `heartbeat()` extends it while work continues.
alter table public.dsp_jobs
    add column if not exists lease_expires_at timestamptz;

comment on column public.dsp_jobs.meta is
    'Submit-time job input (track_id, preset_id, ...) kept separate from result so a reader can tell what the job was asked to do from what it produced.';
comment on column public.dsp_jobs.lease_expires_at is
    'Worker heartbeat deadline. Null once the job reaches a terminal status; a reader past this instant treats the job as dead and reclaimable.';

-- A reader polling `GET /api/jobs/master/{job_id}` filters on this, and the TTL
-- janitor needs an aging index.
create index if not exists dsp_jobs_lease_expires_at_idx
    on public.dsp_jobs (lease_expires_at)
    where lease_expires_at is not null;

-- ── Part 2: sessions, guarded recreate ─────────────────────────────────────
-- The live table is the wrong shape AND empty. Refuse to touch it otherwise:
-- if someone ever parked real rows in that key/value table, dropping it would
-- destroy them and this migration must stop instead of guessing.

do $$
declare
    row_count bigint;
begin
    if to_regclass('public.sessions') is null then
        raise notice 'public.sessions does not exist; creating it with the correct schema';
        return;
    end if;

    select count(*) into row_count from public.sessions;

    if row_count > 0 then
        raise exception
            'public.sessions has % row(s) and the wrong schema; refusing to drop. '
            'Migrate the data by hand, then re-run this migration.', row_count;
    end if;

    raise notice 'public.sessions is empty and wrong-shaped; recreating it';
end
$$;

-- Only reached when the table is absent or provably empty.
drop table if exists public.sessions;

create table public.sessions (
    -- Opaque id generated by the app (uuid4 hex), never by the DB.
    -- PRIMARY KEY is load-bearing, not decoration: `upsert_many()` calls
    -- `.upsert(payload)` with no `on_conflict`, so PostgREST resolves the
    -- conflict target from this constraint. Without it, every save fails.
    session_id text primary key,

    -- Mirrors the Python `ProcessingStatus` StrEnum. CHECKed so a typo can
    -- never become a status the client cannot classify.
    status text not null default 'uploaded'
        check (status in ('uploaded', 'analyzing', 'processing',
                          'completed', 'error')),

    -- The complete SessionData, exactly as `model_dump(mode="json")` emits it.
    -- One jsonb rather than a column per field: SessionData is a Pydantic model
    -- with nested models and enums, so a column-per-field upsert would silently
    -- drop keys Postgres does not know about.
    payload jsonb not null default '{}'::jsonb,

    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

comment on table public.sessions is
    'Durable AudioMind session state. Read/written by AudioMind with the service_role key.';
comment on column public.sessions.payload is
    'Verbatim SessionData.model_dump(mode="json"). Single source of truth; the status column is a queryable extract, not a copy to keep in sync.';

-- Bounded sweep for the TTL janitor. `demo_guard.prune_expired_sessions` only
-- ever sees the in-memory dict, which is empty on a cold start, so the DB
-- needs its own aging index.
create index if not exists sessions_updated_at_idx
    on public.sessions (updated_at desc);

-- RLS on, zero policies: service_role bypasses it, anon/authenticated get
-- nothing. Session rows carry R2 keys and full analysis payloads, and the
-- download URL is signed server-side for that reason.
alter table public.sessions enable row level security;

-- ── Part 3: verify, loudly ─────────────────────────────────────────────────
-- The whole class of bug this migration fixes is a mismatch that nobody says
-- out loud. If anything is still missing, say so here instead of letting the
-- service fall back to a file mirror at boot.

do $$
declare
    missing text;
begin
    select string_agg(required.tbl || '.' || required.col, ', ')
      into missing
      from (values
              ('dsp_jobs.job_id'), ('dsp_jobs.kind'), ('dsp_jobs.status'),
              ('dsp_jobs.progress'), ('dsp_jobs.stage'), ('dsp_jobs.session_id'),
              ('dsp_jobs.meta'), ('dsp_jobs.result'), ('dsp_jobs.error'),
              ('dsp_jobs.created_at'), ('dsp_jobs.updated_at'),
              ('dsp_jobs.lease_expires_at'),
              ('sessions.session_id'), ('sessions.status'),
              ('sessions.payload'), ('sessions.created_at'),
              ('sessions.updated_at')
           ) as required(column)
     where not exists (
               select 1
                 from pg_attribute a
                 join pg_class c on c.oid = a.attrelid
                 join pg_namespace n on n.oid = c.relnamespace
                where n.nspname = 'public'
                  and c.relname = split_part(required.column, '.', 1)
                  and a.attname = split_part(required.column, '.', 2)
                  and a.attnum > 0
                  and not a.attisdropped
           );

    if missing is not null then
        raise exception 'schema drift still present: %', missing;
    end if;

    raise notice 'AudioMind job + session schema verified';
end
$$;